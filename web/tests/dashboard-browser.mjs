import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {join} from 'node:path';

const base=process.env.PULSE_DASHBOARD_UI_BASE;
const session=process.env.PULSE_DASHBOARD_UI_SESSION;
const role=process.env.PULSE_DASHBOARD_UI_ROLE??'admin';
const cdp=process.env.PULSE_DASHBOARD_UI_CDP;
assert(base&&session&&cdp,'owned App/browser fixture required');
const browser=await chromium.connectOverCDP(cdp);
const context=await browser.newContext({viewport:{width:1280,height:880}});
try {
 await context.addCookies([{name:'pulsemedia_session',value:session,url:base,httpOnly:true,sameSite:'Lax'}]);
 const page=await context.newPage();
 page.setDefaultTimeout(15000);
 const errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 // Protocol-only empty feeds; subscription records, media kinds, auth and status use real App/PG.
 await page.route(base+'/api/v1/indexers',route=>route.fulfill({status:200,contentType:'application/json',body:'{"items":[]}'}));
 await page.route(base+'/api/v1/discover?*',route=>route.fulfill({status:200,contentType:'application/json',body:'{"results":[]}'}));
 const movie=page.locator('.stat-card-modern').filter({hasText:'电影监控订阅'}).locator('strong');
 const tv=page.locator('.stat-card-modern').filter({hasText:'电视剧连载追更'}).locator('strong');
 const refresh=page.getByTitle('刷新系统状态',{exact:true});
 const subscriptions=base+'/api/v1/subscriptions';
 const initial=page.waitForResponse(response=>response.url()===subscriptions&&response.ok());
 const statusResponse=page.waitForResponse(response=>response.url()===base+'/api/v1/system/status');
 await page.goto(base+'/');
 const records=(await (await initial).json()).items;
 const status=await statusResponse;
 assert.equal(status.status(),200,'current member must retain basic system status');
 const system=await status.json();
 if(role==='member')assert.equal(Object.hasOwn(system,'data_dir'),false,'member response leaked data directory');
 else assert.equal(typeof system.data_dir,'string','admin data directory missing');
 assert.equal(records.filter(item=>item.media_type==='movie').length,1);
 assert.equal(records.filter(item=>item.media_type==='tv'&&item.scope_type==='all').length,1);
 assert.equal(records.filter(item=>item.media_type==='tv'&&item.scope_type==='selected').length,1);
 await page.waitForFunction(()=>document.querySelector('.stat-card-modern strong')?.textContent==='1');
 assert.equal(await movie.innerText(),'1');
 assert.equal(await tv.innerText(),'2');
 await refresh.waitFor();
 await page.waitForFunction(()=>!document.querySelector('[title="刷新系统状态"]')?.disabled);
 const shot=process.env.PULSE_DASHBOARD_ARTIFACT_DIR;
 if(role==='admin')await page.getByText('应用数据主目录',{exact:true}).waitFor();
 else assert.equal(await page.getByText('应用数据主目录',{exact:true}).count(),0,'member dashboard exposed private directory row');
 if(shot)await page.screenshot({path:join(shot,`dashboard-${role}-desktop.png`),fullPage:true});
 let release;
 let entered;
 const held=new Promise(resolve=>{release=resolve});
 const requested=new Promise(resolve=>{entered=resolve});
 await page.route(subscriptions,async route=>{entered();await held;await route.continue()});
 await refresh.click();
 await requested;
 assert.equal(await refresh.isDisabled(),true);
 assert.equal(await page.getByText('控制台状态已刷新',{exact:true}).count(),0,'success appeared before actual subscription response');
 release();
 await page.getByText('控制台状态已刷新',{exact:true}).waitFor();
 assert.equal(await refresh.isEnabled(),true);
 await page.locator('.toast-card.success').click();
 await page.unroute(subscriptions);
 await page.route(subscriptions,route=>route.fulfill({status:503,contentType:'application/problem+json',body:'{"code":"UNAVAILABLE","message":"owned fixture fault"}'}));
 await refresh.click();
 await page.getByText('部分数据未刷新',{exact:true}).waitFor();
 assert.match(await page.getByRole('alert').innerText(),/订阅统计/);
 assert.equal(await movie.innerText(),'1');
 assert.equal(await tv.innerText(),'2');
 assert.equal(await page.getByText('控制台状态已刷新',{exact:true}).count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{}))));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile horizontal overflow');
 const horizontalLabels=await page.locator('.welcome-actions .btn-banner-action span').evaluateAll(labels=>labels.every(label=>label.getBoundingClientRect().height<parseFloat(getComputedStyle(label).fontSize)*2));
 assert.equal(horizontalLabels,true,'mobile action labels must stay on one line');
 const valuesFit=await page.locator('.sys-item-val').evaluateAll(values=>values.every(value=>value.scrollWidth<=value.clientWidth+1));
 assert.equal(valuesFit,true,'system values must wrap within their cards');
 if(shot)await page.screenshot({path:join(shot,`dashboard-${role}-mobile.png`),fullPage:true});
 await page.locator('.toast-card.error').click();
 await page.unroute(subscriptions);
 await page.route(subscriptions,route=>route.abort('failed'));
 await refresh.click();
 await page.getByText('部分数据未刷新',{exact:true}).waitFor();
 assert.equal(await movie.innerText(),'1');
 assert.equal(await tv.innerText(),'2');
 await page.unroute(subscriptions);
 await refresh.click();
 await page.getByText('控制台状态已刷新',{exact:true}).waitFor();
 assert.equal(await page.getByRole('alert').count(),0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'DASHBOARD_BROWSER_PASSED',role,movies:1,tv:2,data_dir_hidden:role==='member',delayed_success_checked:true,http_and_network_failure_preserved:true,recovery:true,page_errors:0}));
} finally {
 await context.close();
 await browser.close();
}
