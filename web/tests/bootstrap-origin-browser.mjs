import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
const base=process.env.PULSE_BOOTSTRAP_BROWSER_BASE;
const foreign=process.env.PULSE_BOOTSTRAP_FOREIGN_BASE;
if(process.env.PULSE_UI_FIXTURE!=='1'||!base||!foreign)throw Error('Explicit disposable bootstrap fixture required');
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-background-networking','--disable-gpu']});
try{
 const page=await browser.newPage();page.setDefaultTimeout(15000);
 const counts=async()=>await (await page.request.get(base+'/fixture/auth-counts')).json();
 assert.deepEqual(await counts(),{users:0,sessions:0});
 await page.goto(foreign);
 const denied=page.waitForResponse(r=>r.url()===base+'/api/v1/auth/setup'&&r.request().method()==='POST');
 await page.evaluate(async(base)=>{await fetch(base+'/api/v1/auth/setup',{method:'POST',mode:'no-cors',credentials:'omit',headers:{'Content-Type':'text/plain'},body:JSON.stringify({username:'foreign-bootstrap',password:'SyntheticBrowserOrigin-5678!'})})},base);
 assert.equal((await denied).status(),403);
 assert.deepEqual(await counts(),{users:0,sessions:0});
 assert.equal((await page.context().cookies(base)).length,0);
 await page.goto(base+'/setup');
 await page.getByRole('heading',{name:'初始化管理员账户',exact:true}).waitFor();
 await page.getByPlaceholder('admin',{exact:true}).fill('browser-bootstrap');
 await page.getByPlaceholder('输入安全密码...',{exact:true}).fill('SyntheticBrowserOrigin-5678!');
 await page.getByPlaceholder('再次输入确认...',{exact:true}).fill('SyntheticBrowserOrigin-5678!');
 const saved=page.waitForResponse(r=>r.url()===base+'/api/v1/auth/setup'&&r.request().method()==='POST');
 await page.locator('form button[type="submit"]').click();
 assert.equal((await saved).status(),200);
 assert.deepEqual(await counts(),{users:1,sessions:1});
 const cookie=(await page.context().cookies(base)).find(c=>c.name==='pulsemedia_session');
 assert.ok(cookie?.httpOnly);assert.equal(cookie.sameSite,'Strict');
 await page.reload();
 assert.equal(await page.evaluate(async()=>(await fetch('/api/v1/auth/me')).status),200);
 assert.equal(await page.evaluate(async()=>(await fetch('/api/v1/auth/setup',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:'browser-bootstrap',password:'SyntheticBrowserOrigin-5678!'})})).status),409);
 assert.deepEqual(await counts(),{users:1,sessions:1});
 assert.equal(await page.evaluate(async()=>(await fetch('/api/v1/auth/logout',{method:'POST'})).status),204);
 assert.deepEqual(await counts(),{users:1,sessions:0});
 await page.goto(base+'/login');
 await page.getByRole('heading',{name:'登录 PulseMedia',exact:true}).waitFor();
 await page.getByPlaceholder('输入管理员用户名...',{exact:true}).fill('browser-bootstrap');
 await page.getByPlaceholder('输入密码...',{exact:true}).fill('SyntheticBrowserOrigin-5678!');
 const login=page.waitForResponse(r=>r.url()===base+'/api/v1/auth/login'&&r.request().method()==='POST');
 await page.locator('form button[type="submit"]').click();
 assert.equal((await login).status(),200);
 assert.deepEqual(await counts(),{users:1,sessions:1});
 console.log(JSON.stringify({passed:true,foreignSimpleRequestDeniedBeforeAdmin:true,noRejectedSessionOrCookie:true,realSetupAndLoginForms:true,sameOriginReloadAndLogout:true,singleAdminAndSession:true,httpOnlyStrictCookie:true}));
}finally{await browser.close()}
