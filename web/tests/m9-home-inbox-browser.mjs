import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { join } from 'node:path';
import { mkdirSync } from 'node:fs';
const env=process.env,base=env.PULSE_M9_RATE_BASE,shots=env.PULSE_M9_RATE_SCREENSHOTS,closePath=env.PULSE_M9_INBOX_CLOSE_PATH;
assert(base&&shots?.startsWith('/data/temp/')&&closePath?.startsWith('/api/v1/media-requests/'));
mkdirSync(shots,{recursive:true});
const browser=await chromium.connectOverCDP(env.PULSE_M9_RATE_CDP),context=await browser.newContext({viewport:{width:1440,height:960},colorScheme:'dark',reducedMotion:'reduce',serviceWorkers:'block'});
let checks=0;const check=(v,m)=>{assert(v,m);checks++;};
try {
 const external=[],writes=[],errors=[];
 await context.route('**/*',route=>{const url=new URL(route.request().url());if(url.origin===base)return route.continue();external.push(url.origin);return route.abort();});
 const cookie=value=>context.addCookies([{name:'pulsemedia_session',value,url:base,httpOnly:true,sameSite:'Lax'}]);
 await cookie(env.PULSE_M9_RATE_SESSION);
 const page=await context.newPage();page.setDefaultTimeout(15000);
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/')&&r.method()!=='GET')writes.push(new URL(r.url()).pathname);});
 const rates=()=>page.getByRole('region',{name:'全局传输速率',exact:true}),inbox=()=>page.getByRole('region',{name:'待审批提醒',exact:true});
 const native=async()=>{const result=await context.request.get(base+'/__m9_rates/counters');assert.equal(result.status(),200);return result.json();};
 const control=async mode=>assert.equal((await context.request.post(base+'/__m9_rates/'+mode)).status(),204);
 const ready=async count=>{await inbox().getByLabel(`待审批 ${count} 项`,{exact:true}).waitFor();await rates().locator('.global-rate-download .global-rate-value').filter({hasText:'576.0 KiB/s'}).waitFor();};
 const capture=async name=>{
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  const a=await inbox().boundingBox(),b=await rates().boundingBox();assert(a&&b);
  const size=page.viewportSize();
  await page.screenshot({path:join(shots,`${name}.png`),fullPage:true,clip:{x:0,y:Math.max(0,Math.floor(a.y-8)),width:size.width,height:Math.ceil(b.y+b.height-a.y+16)}});
 };
 await page.goto(base,{waitUntil:'domcontentloaded'});await ready('3');
 check(await rates().getByText('128.0 KiB/s',{exact:true}).count()>=1,'native upload missing');
 check(await rates().getByRole('img').count()===2,'native history curves missing');
 const before=await native();check(before.reads===4&&before.unexpected===0,'native sample fixture invalid');
 for(const width of [1440,768,375,320]){
  await page.setViewportSize({width,height:960});
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{}))));
  const bounds=await inbox().evaluate(node=>({page:document.documentElement.scrollWidth,width:innerWidth,elements:[...node.querySelectorAll('h2,strong,p,button,a')].map(el=>{const b=el.getBoundingClientRect();return {left:b.left,right:b.right,width:b.width,height:b.height,tag:el.tagName};})}));
  check(bounds.page<=width+1,`home overflow at ${width}`);
  check(bounds.elements.every(b=>b.width===0||b.left>=-1&&b.right<=width+1),`inbox content overflow at ${width}`);
  check(bounds.elements.filter(b=>b.tag==="BUTTON"||b.tag==="A").every(b=>b.height>=44),`inbox touch controls below 44px at ${width}`);
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await capture(`home-inbox-${width}`);
 }
 check(writes.length===0,'homepage navigation caused a write');
 await inbox().getByRole('link',{name:'处理待审批请求',exact:true}).click();
 await page.getByRole('heading',{name:'待审批请求',exact:true}).waitFor();
 await page.waitForFunction(()=>document.querySelectorAll('li[data-request-id]').length===3);
 check(new URL(page.url()).searchParams.get('state')==='pending','badge lost pending filter');
 check(writes.length===0,'inbox link auto-submitted a command');
 const id=closePath.split('/').at(-2),row=page.locator(`[data-request-id="${id}"]`);
 await row.getByText('处理此请求',{exact:true}).click();
 const form=row.getByRole('form',{name:`关闭请求 ${id}`,exact:true});
 await form.getByRole('textbox',{name:/^原因/}).fill('家庭管理员已核对，明确拒绝此请求。');
 await row.screenshot({path:join(shots,"home-inbox-pending.png"),style:"header.topbar { visibility: hidden !important; }"});
 const response=page.waitForResponse(r=>new URL(r.url()).pathname===closePath&&r.request().method()==='POST');
 await form.getByRole('button',{name:'拒绝请求',exact:true}).click();
 check((await response).status()===200,'explicit rejection did not commit');
 await page.getByRole('button',{name:'刷新当前页',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('li[data-request-id]').length===2);
 check(await page.locator(`[data-request-id="${id}"]`).count()===0,'terminal request stayed in pending queue');
 await page.goto(base,{waitUntil:'domcontentloaded'});await ready('2');
 check(JSON.stringify(await native())===JSON.stringify(before),'GET or rejection contacted a downloader');
 await control('failure');
 await rates().getByRole('button',{name:'刷新速率',exact:true}).click();
 await rates().getByText('未知',{exact:true}).first().waitFor();
 await page.route('**/api/v1/media-requests/summary',async route=>{const response=await route.fetch();assert.equal(response.status(),200);await route.fulfill({status:503,contentType:'application/problem+json',body:JSON.stringify({code:'UNAVAILABLE'})});},{times:1});
 await inbox().getByRole('button',{name:'刷新提醒',exact:true}).click();
 await inbox().getByRole('alert').filter({hasText:'读取失败'}).waitFor();
 check(await inbox().getByLabel('待审批数量未知',{exact:true}).isVisible(),'failed read reused the old count');
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await capture("home-inbox-failure");
 await control('success');
 await inbox().getByRole('button',{name:'刷新提醒',exact:true}).click();
 await rates().getByRole('button',{name:'刷新速率',exact:true}).click();await ready('2');
 await cookie(env.PULSE_M9_RATE_MEMBER_SESSION);await page.evaluate(()=>window.__m9RatesAuth.checkStatus());
 await inbox().waitFor({state:'detached'});await rates().waitFor({state:'detached'});
 check((await context.request.get(base+'/api/v1/media-requests/summary')).status()===403,'member read global inbox');
 await cookie(env.PULSE_M9_RATE_SESSION);await page.evaluate(()=>window.__m9RatesAuth.checkStatus());await ready('2');
 const after=await native();check(after.reads===8&&after.unexpected===0,'page made extra native calls');
 check(writes.length===1&&writes[0]===closePath,'unexpected API writes');check(errors.length===0,`page errors: ${errors.join(';')}`);check(external.length===0,'external network request');
 console.log(`M9_HOME_INBOX_CHROME_PASS checks=${checks} viewports=1440_768_375_320 screenshots=6 rates=REAL_NATIVE pending=3_TO_2 link=PENDING_FILTER close=REAL_EXPLICIT_POST member=REAL_COOKIE read_failure=UNKNOWN snapshots=GO_FULL_NON_AUTH`);
} finally {await context.close();await browser.close();}
