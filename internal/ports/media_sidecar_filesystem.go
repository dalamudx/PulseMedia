package ports

import (
	"context"
	"errors"
)

const MaxSidecarBytes = 8 * 1024 * 1024

var ErrSidecarRequest = errors.New("invalid sidecar request")

// SidecarDirectoryIdentity excludes mutable directory size and mtime.
type SidecarDirectoryIdentity struct{ Device, Inode int64 }

// SidecarRequest binds a regular source file and its proven ancestor directory.
// Paths are canonical root-relative paths; "." denotes the root directory.
// Content must remain immutable until the synchronous call returns.
type SidecarRequest struct {
	SourceRelative       string
	SourceIdentity       FileIdentity
	DestinationDirectory string
	DestinationIdentity  SidecarDirectoryIdentity
	Name                 string
	Content              []byte
}

type SidecarDisposition string

const (
	SidecarNotPublished     SidecarDisposition = "not_published"
	SidecarCreated          SidecarDisposition = "created"
	SidecarPreservedRegular SidecarDisposition = "preserved_regular"
	SidecarUnsafeExisting   SidecarDisposition = "unsafe_existing"
	SidecarUncertain        SidecarDisposition = "uncertain"
)

// SidecarResult never authenticates an existing file as generated by this job.
// Published records actual publication even if a subsequent failure makes the
// outcome uncertain. An uncertain final file must be preserved for observation.
type SidecarResult struct {
	Disposition SidecarDisposition
	Published   bool
	Identity    FileIdentity
}

// MediaSidecarFilesystem publishes missing metadata, never replacing an entry.
// The caller owns LockRoots until all I/O and cleanup have actually returned and
// validates the configured namespace, root identity, marker and job lease itself.
// InspectSidecarDirectory is observation, not authorization of a work directory.
type MediaSidecarFilesystem interface {
	RootFilesystem
	InspectSidecarDirectory(context.Context, TransferRoot, string) (SidecarDirectoryIdentity, error)
	PublishSidecar(context.Context, TransferRoot, SidecarRequest) (SidecarResult, error)
}
