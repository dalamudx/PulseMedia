func managedFixture(t *testing.T) (sidecarFixture, ports.ManagedSidecarContent, uuid.UUID) {
	t.Helper()
	f := newSidecarFixture(t)
	if _, err := f.root.PublishSidecar(t.Context(), f.req); err != nil {
		t.Fatal(err)
	}
	old, err := NewFilesystem().ReadManagedSidecar(t.Context(), &capability{f.root}, f.req)
	if err != nil {
		t.Fatal(err)
	}
	if old.Hash != managedHash(f.req.Content) || old.Identity == f.req.SourceIdentity {
		t.Fatal("invalid original evidence")
	}
	f.req.Content = []byte("<movie>updated metadata</movie>")
	return f, old, uuid.New()
}

func managedPaths(f sidecarFixture, permit uuid.UUID) (string, string) {
	base := filepath.Join(filepath.Dir(f.final()), ".pulsemedia-update-"+permit.String()+"-"+f.req.Name)
	return base + ".bak", base + ".stage"
}

func assertManagedBytes(t *testing.T, path string, want []byte) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil || string(got) != string(want) {
		t.Fatalf("%s: %q, %v; want %q", path, got, err, want)
	}
}

func TestManagedSidecarReplace(t *testing.T) {
	for _, name := range []string{"movie.nfo", "tvshow.nfo", "poster.jpg"} {
		t.Run(name, func(t *testing.T) {
			f := newSidecarFixture(t)
			f.req.Name = name
			if _, err := f.root.PublishSidecar(t.Context(), f.req); err != nil {
				t.Fatal(err)
			}
			fs := NewFilesystem()
			old, err := fs.ReadManagedSidecar(t.Context(), &capability{f.root}, f.req)
			if err != nil {
				t.Fatal(err)
			}
			f.req.Content = []byte("new generated bytes")
			permit := uuid.New()
			out, err := fs.ReplaceManagedSidecar(t.Context(), &capability{f.root}, f.req, old, permit)
			if err != nil || !out.Published || out.Disposition != SidecarCreated || out.Identity == old.Identity {
				t.Fatalf("%+v %v", out, err)
			}
			assertManagedBytes(t, f.final(), f.req.Content)
			backup, stage := managedPaths(f, permit)
			assertManagedBytes(t, backup, old.Content)
			backupID, err := f.root.Inspect(filepath.Join(f.req.DestinationDirectory, filepath.Base(backup)))
			if err != nil || backupID != old.Identity {
				t.Fatalf("backup identity: %+v %v", backupID, err)
			}
			current, err := fs.ReadManagedSidecar(t.Context(), &capability{f.root}, f.req)
			if err != nil || current.Identity != out.Identity || current.Hash != managedHash(f.req.Content) {
				t.Fatalf("published identity: %+v %v", current, err)
			}
			info, err := os.Stat(f.final())
			if err != nil || info.Mode().Perm() != 0644 {
				t.Fatalf("permissions: %v %v", info, err)
			}
			if _, err := os.Lstat(stage); !errors.Is(err, os.ErrNotExist) {
				t.Fatalf("stage retained on success: %v", err)
			}
			out, err = fs.ReplaceManagedSidecar(t.Context(), &capability{f.root}, f.req, current, permit)
			if err == nil || out.Published {
				t.Fatalf("permit replay: %+v %v", out, err)
			}
			assertManagedBytes(t, backup, old.Content)
			f.assertSource(t)
		})
	}
}

func TestManagedSidecarRejectsInvalidEvidence(t *testing.T) {
	for _, kind := range []string{"name", "directory", "hash", "content", "device", "inode", "size", "mtime", "changed_bytes_same_identity", "hardlink", "video_inode", "symlink", "directory_entry", "empty", "oversize", "nil_permit", "bad_name", "escape", "source_identity", "directory_identity"} {
		t.Run(kind, func(t *testing.T) {
			f, old, permit := managedFixture(t)
			switch kind {
			case "name":
				old.Name = "tvshow.nfo"
			case "directory":
				old.Directory = "Show"
			case "hash":
				old.Hash = "wrong"
			case "content":
				old.Content = []byte("wrong")
			case "device":
				old.Identity.Device++
			case "inode":
				old.Identity.Inode++
			case "size":
				old.Identity.Size++
			case "mtime":
				old.Identity.Mtime++
			case "changed_bytes_same_identity":
				info, err := os.Stat(f.final())
				if err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(f.final(), []byte(strings.Repeat("x", len(old.Content))), 0600); err != nil {
					t.Fatal(err)
				}
				if err := os.Chtimes(f.final(), info.ModTime(), info.ModTime()); err != nil {
					t.Fatal(err)
				}
			case "hardlink":
				if err := os.Link(f.final(), f.final()+".manual-link"); err != nil {
					t.Fatal(err)
				}
			case "video_inode":
				if err := os.Remove(f.final()); err != nil {
					t.Fatal(err)
				}
				if err := os.Link(filepath.Join(f.path, f.req.SourceRelative), f.final()); err != nil {
					t.Fatal(err)
				}
			case "symlink":
				if err := os.Remove(f.final()); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink("video.mkv", f.final()); err != nil {
					t.Fatal(err)
				}
			case "directory_entry":
				if err := os.Remove(f.final()); err != nil {
					t.Fatal(err)
				}
				if err := os.Mkdir(f.final(), 0700); err != nil {
					t.Fatal(err)
				}
			case "empty":
				f.req.Content = nil
			case "oversize":
				f.req.Content = make([]byte, MaxSidecarBytes+1)
			case "nil_permit":
				permit = uuid.Nil
			case "bad_name":
				f.req.Name = "logo.png"
			case "escape":
				f.req.DestinationDirectory = "Show/../Show"
			case "source_identity":
				f.req.SourceIdentity.Mtime++
			case "directory_identity":
				f.req.DestinationIdentity.Inode++
			}
			out, err := f.root.replaceManagedSidecar(t.Context(), f.req, old, permit, managedSidecarOps{})
			if err == nil || out.Published || out.Disposition != SidecarNotPublished {
				t.Fatalf("invalid evidence accepted: %+v %v", out, err)
			}
			backup, stage := managedPaths(f, permit)
			for _, path := range []string{backup, stage} {
				if _, err := os.Lstat(path); !errors.Is(err, os.ErrNotExist) {
					t.Fatalf("unexpected artifact %s: %v", path, err)
				}
			}
		})
	}
}

func TestManagedSidecarFaults(t *testing.T) {
	for _, kind := range []string{"partial_write", "zero_write", "invalid_write", "stage_sync", "backup_exists", "backup_race", "stage_exists", "manual_before_displace", "manual_at_rename", "manual_after_displace", "changed_backup", "hardlink_after_displace", "publish_failure", "restore_conflict", "displace_failure", "displace_effect_error", "publish_effect_error", "directory_sync", "published_sync", "stage_substitution", "source_replaced", "parent_replaced", "root_replaced", "cancel_staged", "cancel_displaced", "cancel_published", "manual_after_publish"} {
		t.Run(kind, func(t *testing.T) {
			f, old, permit := managedFixture(t)
			backup, stage := managedPaths(f, permit)
			ctx, cancel := context.WithCancel(t.Context())
			defer cancel()
			ops := managedSidecarOps{}
			put := func(path string, body []byte) {
				t.Helper()
				if err := os.WriteFile(path, body, 0600); err != nil {
					t.Fatal(err)
				}
			}
			move := func(from, to string) {
				t.Helper()
				if err := os.Rename(from, to); err != nil {
					t.Fatal(err)
				}
			}
			manual := []byte("manual content must survive")
			writes, syncs, renames := 0, 0, 0
			ops.write = func(fd int, b []byte) (int, error) {
				writes++
				if kind == "partial_write" {
					n, e := unix.Write(fd, b[:min(3, len(b))])
					if e != nil {
						return n, e
					}
					return n, unix.EIO
				}
				if kind == "zero_write" {
					return 0, nil
				}
				if kind == "invalid_write" {
					return len(b) + 1, nil
				}
				return unix.Write(fd, b)
			}
			ops.sync = func(fd int) error {
				syncs++
				if kind == "stage_sync" && syncs == 1 || kind == "directory_sync" && syncs == 2 || kind == "published_sync" && syncs == 3 {
					return unix.EIO
				}
				return unix.Fsync(fd)
			}
			ops.rename = func(a int, from string, b int, to string, flags uint) error {
				if flags != unix.RENAME_NOREPLACE {
					t.Fatal("overwriting rename")
				}
				renames++
				if kind == "manual_at_rename" && renames == 1 {
					move(f.final(), f.final()+".old")
					put(f.final(), manual)
				}
				if kind == "displace_failure" && renames == 1 {
					return unix.EIO
				}
				if (kind == "publish_failure" || kind == "restore_conflict") && renames == 2 {
					return unix.EIO
				}
				err := unix.Renameat2(a, from, b, to, flags)
				if err == nil && (kind == "displace_effect_error" && renames == 1 || kind == "publish_effect_error" && renames == 2) {
					return unix.EIO
				}
				return err
			}
			ops.checkpoint = func(point string) {
				switch {
				case kind == "backup_race" && point == "before_displace":
					put(backup, manual)
				case kind == "manual_before_displace" && point == "before_displace":
					move(f.final(), f.final()+".old")
					put(f.final(), manual)
				case kind == "manual_after_displace" && point == "displaced":
					put(f.final(), manual)
				case kind == "changed_backup" && point == "displaced":
					put(backup, manual)
				case kind == "hardlink_after_displace" && point == "displaced":
					if err := os.Link(backup, backup+".link"); err != nil {
						t.Fatal(err)
					}
				case kind == "restore_conflict" && point == "before_restore":
					put(f.final(), manual)
				case kind == "stage_substitution" && point == "before_publish":
					move(stage, stage+".owned")
					put(stage, manual)
				case kind == "source_replaced" && point == "before_publish":
					path := filepath.Join(f.path, f.req.SourceRelative)
					move(path, path+".old")
					put(path, manual)
				case kind == "parent_replaced" && point == "before_publish":
					path := filepath.Join(f.path, "Show")
					move(path, path+".old")
					if err := os.Mkdir(path, 0700); err != nil {
						t.Fatal(err)
					}
				case kind == "root_replaced" && point == "before_publish":
					move(f.path, f.path+".moved")
					t.Cleanup(func() {
						if err := os.RemoveAll(f.path + ".moved"); err != nil {
							t.Error(err)
						}
					})
					if err := os.Mkdir(f.path, 0700); err != nil {
						t.Fatal(err)
					}
				case kind == "cancel_staged" && point == "staged", kind == "cancel_displaced" && point == "displaced", kind == "cancel_published" && point == "published":
					cancel()
				case kind == "manual_after_publish" && point == "published":
					move(f.final(), f.final()+".created")
					put(f.final(), manual)
				}
			}
			if kind == "backup_exists" {
				put(backup, manual)
			}
			if kind == "stage_exists" {
				put(stage, manual)
			}
			out, err := f.root.replaceManagedSidecar(ctx, f.req, old, permit, ops)
			if err == nil || out.Disposition == SidecarCreated {
				t.Fatalf("fault accepted: %+v %v writes=%d syncs=%d", out, err, writes, syncs)
			}
			beforeMutation := kind == "partial_write" || kind == "zero_write" || kind == "invalid_write" || kind == "stage_sync" || kind == "backup_exists" || kind == "stage_exists" || kind == "manual_before_displace" || kind == "cancel_staged"
			if beforeMutation && (out.Published || out.Disposition != SidecarNotPublished) {
				t.Fatalf("pre-mutation: %+v", out)
			}
			if !beforeMutation && out.Disposition != SidecarUncertain {
				t.Fatalf("missing uncertainty: %+v %v", out, err)
			}
			switch kind {
			case "manual_before_displace", "manual_at_rename", "manual_after_displace", "restore_conflict", "manual_after_publish":
				assertManagedBytes(t, f.final(), manual)
			case "changed_backup":
				assertManagedBytes(t, f.final(), manual)
			case "backup_exists", "backup_race":
				assertManagedBytes(t, backup, manual)
				assertManagedBytes(t, f.final(), old.Content)
			case "published_sync", "cancel_published", "publish_effect_error":
				assertManagedBytes(t, f.final(), f.req.Content)
				assertManagedBytes(t, backup, old.Content)
			case "displace_effect_error":
				assertManagedBytes(t, backup, old.Content)
				if _, e := os.Lstat(f.final()); !errors.Is(e, os.ErrNotExist) {
					t.Fatalf("ambiguous displacement target: %v", e)
				}
			case "root_replaced", "parent_replaced": // Pinned old namespace holds the restored file and staging evidence.
			default:
				assertManagedBytes(t, f.final(), old.Content)
			}
			if kind == "partial_write" || kind == "zero_write" || kind == "invalid_write" || kind == "stage_sync" || kind == "cancel_staged" {
				if _, e := os.Lstat(stage); !errors.Is(e, os.ErrNotExist) {
					t.Fatalf("pre-mutation staging cleanup: %v", e)
				}
			}
			if kind == "stage_exists" || kind == "stage_substitution" {
				assertManagedBytes(t, stage, manual)
			}
			if kind == "stage_substitution" {
				assertManagedBytes(t, stage+".owned", f.req.Content)
			}
			if kind == "manual_after_displace" || kind == "restore_conflict" || kind == "publish_failure" || kind == "displace_failure" || kind == "displace_effect_error" {
				assertManagedBytes(t, stage, f.req.Content)
			}
		})
	}
}

func TestManagedSidecarCapabilityAndReadValidation(t *testing.T) {
	fs := NewFilesystem()
	f, old, permit := managedFixture(t)
	for _, root := range []ports.TransferRoot{nil, foreignSidecarRoot{}, (*capability)(nil), &capability{}} {
		if _, err := fs.ReadManagedSidecar(t.Context(), root, f.req); !errors.Is(err, ErrIdentity) {
			t.Fatalf("read capability: %v", err)
		}
		if out, err := fs.ReplaceManagedSidecar(t.Context(), root, f.req, old, permit); !errors.Is(err, ErrIdentity) || out.Published {
			t.Fatalf("replace capability: %+v %v", out, err)
		}
	}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	if _, err := fs.ReadManagedSidecar(ctx, nil, f.req); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	if _, err := fs.ReplaceManagedSidecar(ctx, nil, f.req, old, permit); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	for _, kind := range []string{"hardlink", "symlink", "directory", "fifo", "empty", "oversize", "missing", "bad_name", "source_symlink", "parent_symlink"} {
		t.Run(kind, func(t *testing.T) {
			f, _, _ := managedFixture(t)
			switch kind {
			case "hardlink":
				if err := os.Link(f.final(), f.final()+".link"); err != nil {
					t.Fatal(err)
				}
			case "symlink", "directory", "fifo", "empty", "oversize", "missing":
				if err := os.Remove(f.final()); err != nil {
					t.Fatal(err)
				}
				var err error
				switch kind {
				case "symlink":
					err = os.Symlink("video.mkv", f.final())
				case "directory":
					err = os.Mkdir(f.final(), 0700)
				case "fifo":
					err = unix.Mkfifo(f.final(), 0600)
				case "empty":
					err = os.WriteFile(f.final(), nil, 0600)
				case "oversize":
					var file *os.File
					file, err = os.Create(f.final())
					if err == nil {
						err = errors.Join(file.Truncate(MaxSidecarBytes+1), file.Close())
					}
				}
				if err != nil {
					t.Fatal(err)
				}
			case "bad_name":
				f.req.Name = "../movie.nfo"
			case "source_symlink":
				path := filepath.Join(f.path, f.req.SourceRelative)
				if err := os.Rename(path, path+".real"); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink("video.mkv.real", path); err != nil {
					t.Fatal(err)
				}
			case "parent_symlink":
				path := filepath.Join(f.path, "Show")
				if err := os.Rename(path, path+".real"); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink("Show.real", path); err != nil {
					t.Fatal(err)
				}
			}
			content, err := fs.ReadManagedSidecar(t.Context(), &capability{f.root}, f.req)
			if err == nil || len(content.Content) != 0 {
				t.Fatalf("unsafe read: %+v %v", content, err)
			}
		})
	}
}
