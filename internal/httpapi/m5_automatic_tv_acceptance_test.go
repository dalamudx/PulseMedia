// A sequence records trigger execution even when the enclosing UoW rolls back.
// Faults are operation-scoped and removed before retry and before fixture cleanup.
func (h *m5AutomaticTVAcceptance) installFault(t *testing.T, op uuid.UUID, kind string) func() {
	t.Helper()
	condition := "NEW.action='automatic_tv.submission_observed' AND EXISTS(SELECT 1 FROM download_task t WHERE t.id::text=NEW.target_id AND t.operation_id='" + op.String() + "'::uuid)"
	if kind == "import" {
		condition = "NEW.action='transfer.imported' AND EXISTS(SELECT 1 FROM transfer_step s JOIN transfer_plan p ON p.id=s.plan_id WHERE s.id::text=NEW.target_id AND p.operation_id='" + op.String() + "'::uuid)"
	}
	m5InteractiveSQL(t, h.f, `CREATE SEQUENCE m5_tv_fault_seen; CREATE FUNCTION m5_tv_fault() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF `+condition+` THEN PERFORM nextval('m5_tv_fault_seen'); RAISE EXCEPTION 'owned automatic TV tail fault'; END IF; RETURN NEW; END $$; CREATE TRIGGER m5_tv_fault BEFORE INSERT ON audit_log FOR EACH ROW EXECUTE FUNCTION m5_tv_fault()`)
	var once sync.Once
	clear := func() {
		once.Do(func() {
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			defer cancel()
			if _, e := h.f.app.DBPool().Exec(ctx, `DROP TRIGGER IF EXISTS m5_tv_fault ON audit_log; DROP FUNCTION IF EXISTS m5_tv_fault(); DROP SEQUENCE IF EXISTS m5_tv_fault_seen`); e != nil {
				t.Error("owned fault cleanup", e)
			}
		})
	}
	t.Cleanup(clear)
	return clear
}

func (h *m5AutomaticTVAcceptance) awaitFault(t *testing.T) {
	t.Helper()
	m5AutomaticTVWait(t, 60*time.Second, "actual publication trigger rollback", func(ctx context.Context) (bool, error) {
		var seen bool
		e := h.f.app.DBPool().QueryRow(ctx, `SELECT is_called FROM m5_tv_fault_seen`).Scan(&seen)
		return seen, e
	})
}

