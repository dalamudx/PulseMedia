	if e != nil || h.count(t, `SELECT count(*) FROM library_file WHERE root_id=$1 AND rel_path=$2`, h.root, targetRel) != 0 {
		t.Fatal("tail failure left a published target library file", e)
	}
	clear()
	// The native plan lease is two minutes; allow its real expiry and the
	// worker's 30-second retry without editing either authority or clocks.
	h.awaitImported(t, op, 165*time.Second)
	h.assertImported(t, op, receipt)
