func (h *m5AutomaticTVAcceptance) awaitAdd(t *testing.T) uuid.UUID {
	t.Helper()
	select {
	case <-h.addEntered:
	case <-time.After(90 * time.Second):
		t.Fatal("App workers never reached native Add")
	}
	h.mu.Lock()
	op := h.operation
	h.mu.Unlock()
	if h.count(t, `SELECT count(*) FROM automatic_tv_execution_authority WHERE operation_id=$1 AND owner_id=$2 AND subscription_id=$3 AND unit_id=$4 AND root_id=$5 AND client_id=$6 AND snapshot->'target'->>'mapping_mode'='standard' AND snapshot->'target'->>'mapping_revision'='0'`, op, h.member, h.subscription, h.unit, h.root, h.client) != 1 {
		t.Fatal("actual automatic authority did not bind original member/unit/configuration")
	}
	digest := sha256.Sum256(h.raw)
	if h.count(t, `SELECT count(*) FROM automatic_tv_submission_preparation WHERE operation_id=$1 AND info_hash=$2 AND torrent_sha256=$3`, op, h.hash, digest[:]) != 1 {
		t.Fatal("native metainfo seal does not match original torrent bytes/hash")
	}
	h.assertProtected(t, op)
	return op
}

